import type { NextConfig } from 'next';

/**
 * Cache Components выключены нарочно.
 *
 * Этот режим существует, чтобы предварительно отрисовывать статическую
 * оболочку страницы, а динамику подгружать за границами Suspense. Здесь
 * статической оболочки нет вовсе: каждый экран — данные одного человека за
 * один день, и меняются они от каждой галочки. При включённом режиме
 * чтение cookies() вне Suspense становится ошибкой сборки, и пришлось бы
 * оборачивать в границы всё приложение, а также держать `use cache: private`
 * ради сессии — ровно столько работы, сколько нужно, чтобы не получить
 * ничего. Режим без Cache Components документирован и поддерживается, и
 * fetch в нём по умолчанию не кэшируется — что здесь и требуется.
 */
const nextConfig: NextConfig = {
  cacheComponents: false,
  // Предварительная подгрузка частей страницы — из той же модели: кэшировать
  // нечего, предзагружать тоже.
  partialPrefetching: false,

  // Отдельный вывод: в образ едут только нужные файлы, без всего
  // node_modules. Включено заранее, пригодится в чанке 11.
  output: 'standalone',

  turbopack: {
    rules: {
      '*.css': {
        loaders: ['@tailwindcss/turbopack'],
        as: '*.css',
      },
    },
  },

  /**
   * В бою адрес API совпадает с адресом приложения: `/api/*` раздаёт Caddy.
   * В разработке Next слушает 3000, а Go — 3001, поэтому запросы по `/api`
   * переписываются. Без этого cookie сессии не доехала бы: на другом порту
   * это другой источник.
   */
  async rewrites() {
    if (process.env.NODE_ENV === 'production') return [];
    return [
      {
        source: '/api/:path*',
        destination: 'http://127.0.0.1:3001/api/:path*',
      },
    ];
  },
};

export default nextConfig;
