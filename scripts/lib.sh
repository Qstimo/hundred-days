#!/usr/bin/env bash
# Общее для всех скриптов: корень системы, вывод, остановка с объяснением.
#
# Отдельным файлом, а не копией в каждом скрипте: сообщения об ошибках
# должны выглядеть одинаково, иначе читающий журнал развёртывания каждый раз
# заново разбирается, что именно произошло.

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export ROOT

# Цвета только если вывод идёт в терминал: в журнал поедут управляющие
# последовательности и будут мешать читать.
if [ -t 1 ]; then
  C_RED=$'\033[31m'; C_YELLOW=$'\033[33m'; C_GREEN=$'\033[32m'; C_OFF=$'\033[0m'
else
  C_RED=''; C_YELLOW=''; C_GREEN=''; C_OFF=''
fi

step() { printf '\n%s==> %s%s\n' "$C_GREEN" "$1" "$C_OFF"; }
info() { printf '    %s\n' "$1"; }
warn() { printf '%sвнимание:%s %s\n' "$C_YELLOW" "$C_OFF" "$1" >&2; }

# fail останавливает скрипт с объяснением. Без него set -e обрывает работу
# молча, и причину приходится искать в предыдущих строках вывода.
fail() {
  printf '%sостановлено:%s %s\n' "$C_RED" "$C_OFF" "$1" >&2
  exit 1
}

# compose вызывает docker compose из корня системы. Имя проекта задано в
# docker-compose.yml, поэтому каталог вызова значения не имеет — но
# относительные пути к Caddyfile и init-скриптам имеют.
#
# Файлы перечислены явно, и это не формальность: docker-compose.override.yml
# лежит в репозитории и подхватывается сам, а он публикует порты базы и API
# наружу. На машине разработки это нужно, на сервере это дыра.
#
# Какая надстройка берётся, решает HD_EDGE_NETWORK — та самая переменная, что
# отличает сервер от машины разработки:
#
#   задана  — сеть прокси CAIRN: вход приходит по ней, портов стек не
#             публикует вовсе;
#   пусто   — локальные порты: прокси CAIRN рядом нет, и без порта вход
#             в стек исчез бы вместе с ним.
compose() {
  local files=(-f "$ROOT/docker-compose.yml")

  if [ -n "$(env_value HD_EDGE_NETWORK || true)" ]; then
    files+=(-f "$ROOT/docker-compose.server.yml")
  else
    files+=(-f "$ROOT/docker-compose.override.yml")
  fi

  (cd "$ROOT" && docker compose "${files[@]}" "$@")
}

# env_value читает значение переменной из .env, не исполняя файл.
# Через source было бы короче, но файл с паролями исполнять не стоит: любая
# опечатка вида `$(...)` выполнится.
env_value() {
  local key="$1"
  [ -f "$ROOT/.env" ] || return 1
  sed -n "s/^${key}=//p" "$ROOT/.env" | head -1
}
